#!/usr/bin/env bash
set -euo pipefail

# Longer TinyImageNet adapter comparison for separating convergence from the
# short implementation/merge smoke.  All values remain overrideable so that
# the same entrypoint can be used for a smaller GPU probe.
export TINY_IMAGENET_ADAPTER_DATASET="${TINY_IMAGENET_ADAPTER_DATASET:-zh-plus/tiny-imagenet}"
export TINY_IMAGENET_ADAPTER_BUDGET="${TINY_IMAGENET_ADAPTER_BUDGET:-rank32}"
export TINY_IMAGENET_ADAPTER_DEVICE="${TINY_IMAGENET_ADAPTER_DEVICE:-cuda}"
export TINY_IMAGENET_ADAPTER_DTYPE="${TINY_IMAGENET_ADAPTER_DTYPE:-bf16}"
export TINY_IMAGENET_ADAPTER_SEEDS="${TINY_IMAGENET_ADAPTER_SEEDS:-0,1,2}"
export TINY_IMAGENET_ADAPTER_EPOCHS="${TINY_IMAGENET_ADAPTER_EPOCHS:-10}"
export TINY_IMAGENET_ADAPTER_BATCH_SIZE="${TINY_IMAGENET_ADAPTER_BATCH_SIZE:-32}"
export TINY_IMAGENET_ADAPTER_MAX_TRAIN_SAMPLES="${TINY_IMAGENET_ADAPTER_MAX_TRAIN_SAMPLES:-10000}"
export TINY_IMAGENET_ADAPTER_MAX_VALIDATION_SAMPLES="${TINY_IMAGENET_ADAPTER_MAX_VALIDATION_SAMPLES:-2000}"
export TINY_IMAGENET_ADAPTER_LEARNING_RATE="${TINY_IMAGENET_ADAPTER_LEARNING_RATE:-1e-3}"
export TINY_IMAGENET_ADAPTER_TRAIN_CLASSIFIER_HEAD="${TINY_IMAGENET_ADAPTER_TRAIN_CLASSIFIER_HEAD:-1}"
export TINY_IMAGENET_ADAPTER_OUTPUT="${TINY_IMAGENET_ADAPTER_OUTPUT:-output/tiny-imagenet-adapter-long-head-comparison.json}"

exec bash benchmarks/launchers/run_tiny_imagenet_adapter_budget_comparison.sh
